"""Scoring-day sensitivity: are the first-of-month results representative? docs/scoring_day_sensitivity.md.

    .venv/bin/python src/models/scoring_day_sensitivity.py       (make scoring-days)

The backtest scores on the first day of each month. Here the registered LightGBM of each brand scores
other days of its test months too (days 1, 8, 15, 22 and 29), with no new training, and each day is
judged on its own 60-day label, against the recency rule on the same players. Only days on or after the
first test cutoff of the model (out of sample) and with a closed label are used. Features for days that
are not cached need the signals table on S3, so this runs with an SSO session. Aggregates only.
"""

from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

import mlflow
import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(PROJECT_ROOT / p) for p in ("src/evaluation", "src/models", "src/features", "src")]
import churn_labels  # noqa: E402
from build_features import data_available_through, finalise, raw_features  # noqa: E402
from churn_labels import HORIZON_DAYS  # noqa: E402
from evaluate import run_data  # noqa: E402
from segments import add_segment_features, load_segment_model  # noqa: E402
from train import churn_probability, load_calibrator, run_info  # noqa: E402

from evaluation.metrics import top_decile_precision  # noqa: E402

BRANDS = [14, 23, 64, 72, 73]
DAYS_OF_MONTH = (1, 8, 15, 22, 29)
KEY = ["tenant_id", "player_id"]
REPORT = PROJECT_ROOT / "docs/scoring_day_sensitivity.md"
OUT = PROJECT_ROOT / "data/03_output/scoring_day_sensitivity.csv"


def scoring_days(first: dt.date, data_end: dt.date) -> list[dt.date]:
    """Days 1, 8, 15, 22 and 29 from the first test cutoff on, whose 60-day label is closed."""
    days, month = [], dt.date(first.year, first.month, 1)
    while month + dt.timedelta(days=HORIZON_DAYS) <= data_end:
        days += [month.replace(day=d) for d in DAYS_OF_MONTH]
        month = (month + dt.timedelta(days=32)).replace(day=1)
    return [d for d in days if d >= first and d + dt.timedelta(days=HORIZON_DAYS) <= data_end]


def day_metrics(y: np.ndarray, p: np.ndarray, recency: np.ndarray) -> dict:
    model, rec = top_decile_precision(y, p), top_decile_precision(y, recency)
    return {"players": len(y), "churn_rate": y.mean(), "auc": roc_auc_score(y, p), "recency_auc": roc_auc_score(y, recency),
            "precision": model, "recency_precision": rec, "ratio": model / rec}


def brand_rows(brand: int, client, data_end: dt.date) -> list[dict]:
    version = max(client.search_model_versions(f"name='churn_lightgbm_classifier_brand{brand}'"), key=lambda v: int(v.version))
    info = run_info(version.run_id)
    data, split = run_data(info)
    first = pd.to_datetime(data.loc[split == "test", "cutoff_date"]).min().date()
    model = mlflow.lightgbm.load_model(f"runs:/{version.run_id}/model")
    calibrator, segments = load_calibrator(version.run_id), load_segment_model(version.run_id)
    rows = []
    for day in scoring_days(first, data_end):
        raw = raw_features(day, brand)
        X = finalise(raw)
        X = add_segment_features(X, segments) if segments is not None else X
        labels = churn_labels.churn_targets(raw[KEY], day, brand, data_end)[KEY + ["event_60d"]]
        frame = raw[KEY + ["days_since_last_bet"]].assign(p=churn_probability(model, calibrator, X, info["features"]))
        frame = frame.merge(labels, on=KEY).dropna(subset=["event_60d"])
        y = frame["event_60d"].astype(int).to_numpy()
        rows.append({"brand": brand, "model_version": f"v{version.version}", "day": day, "day_of_month": day.day,
                     **day_metrics(y, frame["p"].to_numpy(), frame["days_since_last_bet"].to_numpy())})
        print(f"brand {brand} {day}: AUC {rows[-1]['auc']:.3f}, ratio {rows[-1]['ratio']:.2f}", flush=True)
    return rows


def write(table: pd.DataFrame) -> Path:
    by_day = table.groupby(["brand", "day_of_month"])[["auc", "ratio"]].mean().unstack("day_of_month")
    lines = ["# Scoring-Day Sensitivity", "",
             "The backtest scores on the first day of each month. Here the registered LightGBM of each brand also "
             f"scores days {', '.join(map(str, DAYS_OF_MONTH))} of its test months, with no new training, and each "
             "day is judged on its own 60-day label against the recency rule on the same players. Only days on or "
             "after the first test cutoff of the model and with a closed label. Generated by "
             "`src/models/scoring_day_sensitivity.py` (`make scoring-days`).", "",
             "## Mean by day of the month", "",
             "| Brand | " + " | ".join(f"AUC day {d}" for d in DAYS_OF_MONTH) + " | "
             + " | ".join(f"ratio day {d}" for d in DAYS_OF_MONTH) + " |",
             "|---|" + "---|" * (2 * len(DAYS_OF_MONTH))]
    for b, r in by_day.iterrows():
        cells = [f"{r[('auc', d)]:.3f}" if ('auc', d) in r and pd.notna(r[('auc', d)]) else "" for d in DAYS_OF_MONTH]
        cells += [f"{r[('ratio', d)]:.2f}" if ('ratio', d) in r and pd.notna(r[('ratio', d)]) else "" for d in DAYS_OF_MONTH]
        lines.append(f"| {b} | " + " | ".join(cells) + " |")
    first = table[table["day_of_month"] == 1].groupby("brand")[["auc", "ratio"]].mean()
    other = table[table["day_of_month"] != 1].groupby("brand")[["auc", "ratio"]].mean()
    lines += ["", "## First day against the other days", "",
              "| Brand | AUC day 1 | AUC other days | worst AUC | ratio day 1 | ratio other days | lowest ratio | days | days model beats recency in AUC |",
              "|---|---|---|---|---|---|---|---|---|"]
    for b, g in table.groupby("brand"):
        lines.append(f"| {b} | {first.loc[b, 'auc']:.3f} | {other.loc[b, 'auc']:.3f} | {g['auc'].min():.3f} | "
                     f"{first.loc[b, 'ratio']:.2f} | {other.loc[b, 'ratio']:.2f} | {g['ratio'].min():.2f} | {len(g)} | "
                     f"{(g['auc'] > g['recency_auc']).sum()} of {len(g)} |")
    lines += ["", "## All days", "", "| Brand | Version | Day | Players | Churn | AUC | Recency AUC | Precision | Recency precision | Ratio |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for r in table.itertuples(index=False):
        lines.append(f"| {r.brand} | {r.model_version} | {r.day} | {r.players:,} | {100 * r.churn_rate:.1f}% | {r.auc:.3f} | "
                     f"{r.recency_auc:.3f} | {r.precision:.3f} | {r.recency_precision:.3f} | {r.ratio:.2f} |")
    REPORT.write_text("\n".join(lines) + "\n")
    return REPORT


def run() -> Path:
    mlflow.set_tracking_uri(f"sqlite:///{PROJECT_ROOT / 'mlflow.db'}")
    client = mlflow.MlflowClient()
    data_end = data_available_through()
    table = pd.DataFrame([r for b in BRANDS for r in brand_rows(b, client, data_end)])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    table.to_csv(OUT, index=False)
    return write(table)


if __name__ == "__main__":
    print(f"saved {run()}")
