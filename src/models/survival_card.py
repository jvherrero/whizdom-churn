"""Survival data card (review item P1 10): what the Cox PH model is trained on.

    .venv/bin/python src/models/survival_card.py

Reads the latest training dataset of each brand in data/processed (local files, no S3) and writes
docs/survival_data_card.md: the time scale, right censoring, left truncation, the censoring rate and
the duration distribution, and a check that the survival labels agree with the 60-day churn label.
Aggregates only, never player rows.
"""

from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

import numpy as np
import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT / "src" / "features"))
from build_features import (  # noqa: E402
    HISTORY_DAYS,
    HISTORY_START,
    MIN_HISTORY_DAYS,
    TENURE_CAP_DAYS,
)
from churn_labels import HORIZON_DAYS  # noqa: E402

BRANDS = [14, 23, 64, 72, 73]
PROCESSED_DIR = PROJECT_ROOT / "data/processed"
REPORT = PROJECT_ROOT / "docs/survival_data_card.md"
COLUMNS = ["cutoff_date", "player_id", "days_since_first_bet", "event_60d", "duration_days", "event_observed"]


def dataset(brand: int) -> Path:
    return max(PROCESSED_DIR.glob(f"train_dataset_{brand}_*.parquet"), key=lambda p: p.stat().st_mtime)


def summary(d: pd.DataFrame) -> dict:
    """One brand: censoring, durations and label consistency."""
    d = d.assign(cutoff_date=pd.to_datetime(d["cutoff_date"]))
    data_end = (d["cutoff_date"] + pd.to_timedelta(d["duration_days"], unit="D")).max()
    events = d.loc[d["event_observed"] == 1, "duration_days"]
    later = events[events > 0]
    by_cutoff = 1 - d.groupby("cutoff_date")["event_observed"].mean()
    # event_60d = 1 means the 60-day silence starts on the cutoff day: duration 0 and observed
    consistent = (d["event_60d"].astype(float) == 1) == ((d["duration_days"] == 0) & (d["event_observed"] == 1))
    return {"rows": len(d), "cutoffs": d["cutoff_date"].nunique(), "data_end": data_end.date(),
            "repeated": 1 - d["player_id"].nunique() / len(d),
            "churn_60d": d["event_60d"].astype(float).mean(), "censored": 1 - d["event_observed"].mean(),
            "censored_first": by_cutoff.iloc[0], "censored_last": by_cutoff.iloc[-1],
            "event_at_0": (events == 0).mean() if len(events) else np.nan,
            "later_q": later.quantile([0.25, 0.5, 0.75, 0.95]).round().astype(int).tolist() if len(later) else [],
            "censored_median": d.loc[d["event_observed"] == 0, "duration_days"].median(),
            "consistent": consistent.mean(),
            # tenure is stored as log1p(days), capped at TENURE_CAP_DAYS
            "tenure_capped": (d["days_since_first_bet"] >= np.log1p(TENURE_CAP_DAYS) - 1e-9).mean(),
            "by_cutoff": by_cutoff}


def write(rows: dict[int, dict]) -> Path:
    first_full_tenure = HISTORY_START + dt.timedelta(days=TENURE_CAP_DAYS)
    first_full_history = HISTORY_START + dt.timedelta(days=HISTORY_DAYS)
    data_end = max(r["data_end"] for r in rows.values())
    lines = ["# Survival Data Card (review item P1 10)", "",
             "What the Cox PH model is trained on. Source: the latest training dataset of each brand in "
             "`data/processed/` (`dataset` column below), the same rows as the LightGBM model. "
             "Generated by `src/models/survival_card.py`.", "",
             "## 1. Definition", "",
             "| Item | Definition |", "|---|---|",
             "| Unit | One player on one cutoff (the first day of a month). The same player can appear in several cutoffs. |",
             "| Population | Players with at least one bet in the 30 days up to the cutoff, included (`churn_labels.population`). |",
             "| Time origin | The cutoff (day 0). Every player enters on day 0, active. |",
             f"| Event | The start of the first silence of {HORIZON_DAYS} days or more after the cutoff: the last bet before it "
             f"(day 0 if the player has no bet after the cutoff). The same {HORIZON_DAYS}-day inactivity as the churn label. |",
             "| `duration_days` | The day of the event, or, if censored, the last day with a bet. |",
             f"| `event_observed` | 1 if the {HORIZON_DAYS}-day silence ends on or before the data end ({data_end}); 0 if censored. |",
             f"| Censoring | Administrative only: the data end. A player whose last bet is less than {HORIZON_DAYS} days before "
             "the data end is censored at that last bet. It does not depend on the player, so it is not informative. |", "",
             "## 2. Right censoring and left truncation", "",
             f"- **Right censoring.** The later the cutoff, the shorter the follow-up, so the censoring rate grows from the "
             "first to the last cutoff (table below). Cox PH handles this through `event_observed`. The 30-day probability "
             f"used in `p_churn_30d` only needs the first 30 days; every cutoff of the dataset has at least "
             f"{HORIZON_DAYS} days of follow-up, so all the events up to day 30 are observed.",
             "- **Left truncation (delayed entry).** There is none on the time scale of the model: time counts from the "
             "cutoff, and every player enters on day 0. A player who stopped before the cutoff is not in the population "
             "of that cutoff; this is the definition of the population, not a truncation of the follow-up.",
             f"- **Where the data start matters: the history features.** The source tables start on {HISTORY_START}. "
             f"Tenure (`days_since_first_bet`) is capped at {TENURE_CAP_DAYS} days, so it means the same on every cutoff "
             f"from {first_full_tenure} on (\"{TENURE_CAP_DAYS} days or more\"). On earlier cutoffs (the first "
             "training months of the backtest), players who started before the data look younger than they are. "
             f"The {HISTORY_DAYS}-day history windows are complete only from {first_full_history}. The longest "
             f"window of the other features, {MIN_HISTORY_DAYS} days, is always complete.",
             "- **Consistency with the churn label.** `event_60d` = 1 must mean the event on day 0 and observed. "
             "Share of rows where this holds: column `Label check`.", "",
             "## 3. Censoring and durations by brand", "",
             "| Brand | Rows | Cutoffs | Rows of a repeated player | 60-day churn | Censored | Censored, first / last cutoff "
             "| Events on day 0 | Later events: days p25 / p50 / p75 / p95 | Censored: median days followed "
             "| Tenure at cap | Label check |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for b, r in rows.items():
        q = " / ".join(map(str, r["later_q"]))
        lines.append(f"| {b} | {r['rows']:,} | {r['cutoffs']} | {100 * r['repeated']:.0f}% | {100 * r['churn_60d']:.1f}% "
                     f"| {100 * r['censored']:.1f}% | {100 * r['censored_first']:.0f}% / {100 * r['censored_last']:.0f}% "
                     f"| {100 * r['event_at_0']:.0f}% | {q} | {r['censored_median']:.0f} "
                     f"| {100 * r['tenure_capped']:.0f}% | {100 * r['consistent']:.2f}% |")
    lines += ["", "- **Events on day 0**: share of the observed events that are churn on the cutoff itself "
              "(the `event_60d` = 1 players).",
              "- **Later events**: players who still bet after the cutoff and then stop. Their duration is the day of their last bet.",
              "- **Rows of a repeated player**: the cutoffs are not independent samples (review item P1 11).", "",
              "## 4. Censoring by cutoff", "",
              "| Cutoff | Days of follow-up | " + " | ".join(f"Brand {b}" for b in rows) + " |",
              "|---|---|" + "---|" * len(rows)]
    cutoffs = sorted(set().union(*(r["by_cutoff"].index for r in rows.values())))
    for c in cutoffs:
        cells = [f"{100 * r['by_cutoff'][c]:.0f}%" if c in r["by_cutoff"].index else "" for r in rows.values()]
        lines.append(f"| {c.date()} | {(pd.Timestamp(data_end) - c).days} | " + " | ".join(cells) + " |")
    lines += ["", "## 5. Datasets", ""] + [f"- Brand {b}: `{r['dataset']}`" for b, r in rows.items()]
    REPORT.write_text("\n".join(lines) + "\n")
    return REPORT


if __name__ == "__main__":
    rows = {}
    for b in BRANDS:
        path = dataset(b)
        rows[b] = summary(pd.read_parquet(path, columns=COLUMNS)) | {"dataset": path.name}
    print(f"saved {write(rows)}")
